#!/usr/bin/env python3
"""Sanity-check the site in docs/.

docs/api.html is generated by scripts/gen_api.py, so its content is already
guarded by `git diff --exit-code`. The other three pages are hand-written, and
nothing else in CI looks at them. This script checks the parts a generator
cannot:

  * every relative href and image src resolves inside docs/
  * no page still carries a template marker from api_template.html
  * the engine is the user's wasm build, not the wasm-gc one
  * each skill under docs/skills/ has the frontmatter the registry reads

    python3 scripts/check_docs.py

Exit code is 0 when the site is sound and 1 when it is not, with one line per
problem so the CI log points straight at the file.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"

# Placeholders left in scripts/api_template.html for the generator to fill.
MARKERS = ("<!--RAIL-->", "<!--MAIN-->")

# A couple of strings that must not come back: the engine is the wasm build the
# reader compiles, not the wasm-gc one, and no page is allowed to ship a stub.
FORBIDDEN = {
    "wasm-gc": "the engine is plain wasm",
    "lorem ipsum": "placeholder copy",
    "TODO": "unfinished note",
}

ATTR = re.compile(r"""(?:href|src)\s*=\s*"([^"]*)\"""")
REMOTE = ("http://", "https://", "//", "mailto:", "data:", "#", "javascript:")
# Paths assembled in script are checked by the image sweep below, not as links.
SCRIPTED = re.compile(r"<(script|style)\b[^>]*>.*?</\1>", re.S)


def markup(page: Path) -> str:
    """The page with script and style removed, so only real attributes remain."""
    return SCRIPTED.sub("", page.read_text(encoding="utf-8"))


def check_links(page: Path) -> list[str]:
    problems = []
    seen = set()
    for target in ATTR.findall(markup(page)):
        target = target.strip()
        if not target or target.startswith(REMOTE) or "$" in target or "{" in target:
            continue
        clean = target.split("#", 1)[0].split("?", 1)[0]
        if not clean or clean in seen:
            continue
        seen.add(clean)
        if not (page.parent / clean).exists():
            problems.append(f"{page.name}: broken link {target}")
    return problems


def check_skills() -> list[str]:
    """Each skill is one directory named after the library, with a SKILL.md
    whose frontmatter carries the name and the description an agent decides
    from. Nothing else about the file is checked here; the snippets in it are
    compiled against the published module instead."""
    problems = []
    skills = sorted(p for p in (DOCS / "skills").glob("*/SKILL.md"))
    if not skills:
        return ["docs/skills/ has no skill"]
    for skill in skills:
        text = skill.read_text(encoding="utf-8")
        if not text.startswith("---\n"):
            problems.append(f"{skill}: no frontmatter")
            continue
        end = text.find("\n---\n", 4)
        if end < 0:
            problems.append(f"{skill}: frontmatter is not closed")
            continue
        head = text[4:end]
        fields = {}
        for line in head.splitlines():
            if ":" in line:
                key, value = line.split(":", 1)
                fields[key.strip()] = value.strip()
        name = fields.get("name", "")
        if name != skill.parent.name:
            problems.append(f"{skill}: name {name!r} is not the directory name")
        description = fields.get("description", "")
        if len(description) < 80:
            problems.append(f"{skill}: the description is too short to decide from")
        if len(text) - end < 400:
            problems.append(f"{skill}: the body is too short to be useful")
    return problems


def main() -> int:
    if not DOCS.is_dir():
        print("docs/ is missing")
        return 1

    pages = sorted(DOCS.glob("*.html"))
    if not pages:
        print("docs/ has no pages")
        return 1

    problems = []
    for page in pages:
        text = page.read_text(encoding="utf-8")
        problems += check_links(page)
        for marker in MARKERS:
            if marker in text:
                problems.append(f"{page.name}: unfilled template marker {marker}")
        for needle, why in FORBIDDEN.items():
            if needle in text:
                problems.append(f"{page.name}: {needle!r} left in ({why})")

    problems += check_skills()

    images = sorted(p.name for p in (DOCS / "images").glob("*") if p.is_file())
    referenced = set()
    for page in pages:
        raw = page.read_text(encoding="utf-8")
        for target in ATTR.findall(markup(page)):
            if "images/" in target:
                referenced.add(target.split("images/", 1)[1].split("?", 1)[0])
        # desk.html builds its stock swatches from a JS array, so a plain
        # substring sweep is what proves those files are meant to be there.
        for name in images:
            if f"images/{name}" in raw:
                referenced.add(name)
    unused = [n for n in images if n not in referenced]

    if problems:
        for line in problems:
            print(f"error: {line}")
        return 1

    total = sum(len(ATTR.findall(markup(p))) for p in pages)
    print(f"ok: {len(pages)} pages, {total} links, {len(images)} images"
          + (f" ({len(unused)} unreferenced: {', '.join(unused)})" if unused else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
