"""Write src/sasl/stringprep.mbt: the RFC 3454 tables SASLprep (RFC 4013) uses,
as sorted code point ranges.

The tables are fixed at Unicode 3.2 by the RFC, which is what Python's
`stringprep` module carries, so it is asked about every code point.

    python3 scripts/gen_stringprep.py
"""

import pathlib
import stringprep
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "sasl" / "stringprep.mbt"

TABLES = [
    ("unassigned_32", "in_table_a1", "A.1, code points unassigned in Unicode 3.2"),
    ("nothing", "in_table_b1", "B.1, code points commonly mapped to nothing"),
    ("spaces", "in_table_c12", "C.1.2, non-ASCII space characters"),
    ("ascii_controls", "in_table_c21", "C.2.1, ASCII control characters"),
    ("controls", "in_table_c22", "C.2.2, non-ASCII control characters"),
    ("private_use", "in_table_c3", "C.3, private use"),
    ("noncharacters", "in_table_c4", "C.4, non-character code points"),
    ("surrogates", "in_table_c5", "C.5, surrogate codes"),
    ("not_plain", "in_table_c6", "C.6, inappropriate for plain text"),
    ("not_canonical", "in_table_c7", "C.7, inappropriate for canonical representation"),
    ("display", "in_table_c8", "C.8, change display properties or deprecated"),
    ("tagging", "in_table_c9", "C.9, tagging characters"),
    ("rtl", "in_table_d1", "D.1, characters with bidirectional property R or AL"),
    ("ltr", "in_table_d2", "D.2, characters with bidirectional property L"),
]


def ranges(test):
    out = []
    start = None
    for cp in range(0x110000):
        hit = test(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    body = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_stringprep.py from Python's stringprep module,",
        f"// which carries RFC 3454's tables at Unicode {stringprep.unicodedata.unidata_version}. Do not edit by hand.",
        "",
    ]
    for name, fn, doc in TABLES:
        rs = ranges(getattr(stringprep, fn))
        body.append("///|")
        body.append(f"/// RFC 3454 table {doc}.")
        body.append(f"let {name} : Array[(Int, Int)] = [")
        row = []
        for lo, hi in rs:
            row.append(f"(0x{lo:X}, 0x{hi:X})")
            if len(row) == 6:
                body.append("  " + ", ".join(row) + ",")
                row = []
        if row:
            body.append("  " + ", ".join(row) + ",")
        body.append("]")
        body.append("")
    OUT.write_text("\n".join(body), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
